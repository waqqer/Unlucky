const getErrorMessage = (error: unknown, fallback: string) => {
    if (typeof error === "object" && error !== null && "response" in error) {
        const response = (error as { response?: { data?: { message?: unknown } } }).response

        if (typeof response?.data?.message === "string") {
            return response.data.message
        }
    }

    return fallback
}

const StatsSection = () => {
    const {
        current,
        peak
    } = useContext(OnlineContext)
    const [stats, setStats] = useState<AdminStats | null>(null)
    const [message, setMessage] = useState<string>("")
    const [pending, setPending] = useState<boolean>(false)

    const cards = useMemo(() => ([
        {
            title: "Аккаунты",
            value: stats?.registeredAccounts ?? 0,
            hint: "Всего зарегистрировано",
            icon: "users" as const
        },
        {
            title: "Онлайн",
            value: current,
            hint: "Текущий онлайн",
            icon: "online" as const
        },
        {
            title: "Макс онлайн",
            value: peak,
            hint: "Макс. пользователей единовременно",
            icon: "peak" as const
        },
        {
            title: "Проиграно",
            value: stats?.lossAmount ?? 0,
            hint: "Пользователи проиграли",
            icon: "loss" as const
        },
        {
            title: "Выиграно",
            value: stats?.winsAmount ?? 0,
            hint: "Пользователи выйиграли",
            icon: "win" as const
        },
        {
            title: "Депозиты",
            value: stats?.totalAmount ?? 0,
            hint: "Сумма пополнений",
            icon: "deposit" as const
        }
    ]), [current, peak, stats])

    const load = useCallback(async () => {
        setPending(true)
        setMessage("")

        try {
            setStats(await AdminApi.getStats())
        } catch (error) {
            setMessage(getErrorMessage(error, "Не удалось загрузить статистику"))
        } finally {
            setPending(false)
        }
    }, [])

    useEffect(() => {
        const timeoutId = window.setTimeout(() => {
            void load()
        }, 0)

        return () => window.clearTimeout(timeoutId)
    }, [load])

    return (
        <div className={styles.panel}>
            <div className={styles.header}>
                <div>
                    <h1>Статистика</h1>
                    <p>Общие показатели проекта, онлайна и финансовых итогов.</p>
                </div>

                <div className={styles.headerActions}>
                    <span className={styles.message}>{pending ? "Загрузка..." : message}</span>
                    <Button className={styles.secondary} onClick={load} isDisabled={pending}>Обновить</Button>
                </div>
            </div>

            <div className={styles.statsGrid}>
                {cards.map(card => (
                    <article className={styles.statCard} key={card.title}>
                        <span className={styles.statIcon}>
                            <StatIcon name={card.icon} />
                        </span>
                        <span>{card.title}</span>
                        <strong>{formatNumber(card.value)}</strong>
                        <p>{card.hint}</p>
                    </article>
                ))}
            </div>
        </div>
    )
}

export default memo(StatsSection)
